    // ── Dynamic invocation ──

    public static Object resolveGlobal(EvaluationContext context, String id) {
        ELContext elctx = context.getELContext();

        ValueExpression expr = context.resolveVariable(id);
        if (expr != null) {
            return expr.getValue(elctx);
        }

        elctx.setPropertyResolved(false);
        Object value = elctx.getELResolver().getValue(elctx, null, id);
        if (elctx.isPropertyResolved()) {
            return value;
        }

        MethodClosure method = MethodResolver.getInstance(elctx)
            .resolveGlobalMethod(context.getFunctionMapper(), id);
        if (method != null) {
            return method;
        }

        throw new EvaluationException(elctx, _T(EL_UNDEFINED_IDENTIFIER, id));
    }

    public static Object resolveTarget(EvaluationContext context, String id) {
        ELContext elctx = context.getELContext();

        ValueExpression expr = context.resolveVariable(id);
        if (expr != null)
            return (expr instanceof Closure) ? expr : expr.getValue(elctx);

        MethodClosure method = MethodResolver.getInstance(elctx)
            .resolveGlobalMethod(context.getFunctionMapper(), id);
        if (method != null)
            return method;

        elctx.setPropertyResolved(false);
        return elctx.getELResolver().getValue(elctx, null, id);
    }

    public static Object invokeTarget(EvaluationContext context, String id, Object[] args) {
        ELContext elctx = context.getELContext();
        Object target = resolveTarget(context, id);
        if (target == null)
            throw new EvaluationException(elctx, _T(EL_UNDEFINED_IDENTIFIER, id));

        try {
            return ELEngine.invokeTarget(elctx, target, ELEngine.getCallArgs(args));
        } catch (RuntimeException ex) {
            throw new EvaluationException(elctx, ex);
        }
    }

    public static Object invokeOperator(EvaluationContext context, String name,
                                        Object rhs) {
        ELContext elctx = context.getELContext();

        if (rhs != null) {
            Object result = ELNode.Unary.invokeOperator(elctx, name, rhs);
            if (result != NO_RESULT)
                return result;
        }

        Object target = resolveTarget(context, name);
        if (target == null) {
            throw new EvaluationException(elctx, _T(EL_UNDEFINED_IDENTIFIER, name));
        }

        try {
            Closure[] args = new Closure[1];
            args[0] = new LiteralClosure(rhs);
            return ELEngine.invokeTarget(elctx, target, args);
        } catch (RuntimeException ex) {
            throw new EvaluationException(elctx, ex);
        }
    }

    public static Object invokeOperator(EvaluationContext context, String name,
                                        Object lhs, Object rhs) {
        ELContext elctx = context.getELContext();

        // invoke operator procedure
        Object result = ELNode.Binary.invokeOperator(elctx, name, lhs, rhs);
        if (result != NO_RESULT)
            return result;

        // invoke target procedure
        Object target = resolveTarget(context, name);
        if (target == null) {
            throw new EvaluationException(elctx, _T(EL_UNDEFINED_IDENTIFIER, name));
        }

        try {
            Closure[] args = new Closure[2];
            args[0] = new LiteralClosure(lhs);
            args[1] = new LiteralClosure(rhs);
            return ELEngine.invokeTarget(elctx, target, args);
        } catch (RuntimeException ex) {
            throw new EvaluationException(elctx, ex);
        }
    }

    public static Object invokeDynMethod(ELContext elctx, Object base, Object key, Object[] args) {
        return ELNode.ACCESS.invoke(elctx, base, key, ELEngine.getCallArgs(args));
    }

    public static Object invokeAssignOp(ELContext elctx, int op, Object lhs, Object rhs) {
        String opname = ELNode.opIdentifiers[op];
        Closure[] args = new Closure[1];
        Object result;

        // invoke assignment operator procedure
        if (lhs != null && opname != null) {
            if (lhs instanceof ClosureObject co) {
                args[0] = new LiteralClosure(rhs);
                result = co.invokeSpecial(elctx, opname.concat("="), args);
                if (result != NO_RESULT)
                    return result;
            } else if (!(lhs instanceof Number)) {
                MethodClosure method = MethodResolver.getInstance(elctx)
                    .resolveMethod(lhs.getClass(), opname.concat("="));
                if (method != null) {
                    args[0] = new LiteralClosure(rhs);
                    return method.invoke(elctx, lhs, args);
                }
            }
        }

        // do standard evaluation.
        return switch (op) {
        case Token.ADD -> dynAdd(elctx, lhs, rhs);
        case Token.SUB -> dynSub(elctx, lhs, rhs);
        case Token.MUL -> dynMul(elctx, lhs, rhs);
        case Token.DIV -> dynDiv(elctx, lhs, rhs);
        case Token.REM -> dynRem(elctx, lhs, rhs);
        case Token.POW -> dynPow(elctx, lhs, rhs);
        case Token.BITAND -> dynBitAnd(elctx, lhs, rhs);
        case Token.BITOR -> dynBitOr(elctx, lhs, rhs);
        case Token.XOR -> dynXor(elctx, lhs, rhs);
        case Token.CAT -> dynCat(elctx, lhs, rhs);
        case Token.SHL -> dynShl(elctx, lhs, rhs);
        case Token.SHR -> dynShr(elctx, lhs, rhs);
        case Token.USHR -> dynUShr(elctx, lhs, rhs);
        default -> null;
        };
    }

    // ── Type guard ──

    public static void guardTypeStrict(Object val, int typeId) {
        if (!checkGuardType(val, typeId)) {
            String expected = IRFormat.primTypeName(typeId);
            String actual = val == null ? "null" : val.getClass().getName();
            throw new RuntimeException(_T(IR_TYPE_MISMATCH, expected, actual));
        }
    }

    private static boolean checkGuardType(Object val, int typeId) {
        if (val == null)
            return false;
        return switch (typeId) {
            case IRFormat.T_INT ->
                    val instanceof Integer || val instanceof Short || val instanceof Byte || val instanceof Long;
            case IRFormat.T_LONG ->
                    val instanceof Long || val instanceof Integer || val instanceof Short || val instanceof Byte;
            case IRFormat.T_DOUBLE ->
                    val instanceof Double || val instanceof Float || val instanceof Long || val instanceof Integer;
            case IRFormat.T_BOOL -> val instanceof Boolean;
            case IRFormat.T_STRING -> val instanceof String;
            default -> true;
        };
    }
