  public static Object newRange(Object begin, Object next, Object end) {
    if (isChar(begin) && (next == null || isChar(next)) &&
        (end == null || isChar(end))) {
      char c_begin = getChar(begin);
      int c_step = (next == null) ? 1 : getChar(next) - c_begin;
      if (end == null) {
        return CharRanges.createUnboundedRange(c_begin, c_step);
      } else {
        char c_end = getChar(end);
        return CharRanges.createCharRange(c_begin, c_end, c_step);
      }
    } else {
      long l_begin = TypeCoercion.coerceToLong(begin);
      long l_step = (next == null) ? 1
                                   : TypeCoercion.coerceToLong(next) - l_begin;
      if (end == null) {
        return Ranges.createUnboundedRange(l_begin, l_step);
      } else {
        long l_end = TypeCoercion.coerceToLong(end);
        return Ranges.createRange(l_begin, l_end, l_step);
      }
    }
  }

  private static boolean isChar(Object o) {
    if (o instanceof Character) {
      return true;
    } else if (o instanceof String) {
      return ((String)o).length() == 1;
    } else {
      return false;
    }
  }

  private static char getChar(Object o) {
    if (o instanceof Character) {
      return (Character)o;
    } else if (o instanceof String) {
      return ((String)o).charAt(0);
    } else {
      throw new AssertionError();
    }
  }

  public static Object newXML(EvaluationContext env, Object tag,
                              Object[] att_names, Object[] att_values,
                              Object[] children) {
    ELContext elctx = env.getELContext();

    try {
      Document doc = XmlNode.getContextDocument(elctx);
      Element elem;
      String name = TypeCoercion.coerceToString(tag);
      String prefix, uri;
      int colon;

      // handle element namespace
      colon = name.indexOf(':');
      if (colon == -1)
        prefix = XMLConstants.DEFAULT_NS_PREFIX;
      else
        prefix = name.substring(0, colon);
      uri = env.getURI(prefix);
      if (uri == null)
        elem = doc.createElement(name);
      else
        elem = doc.createElementNS(uri, name);

      // set element attributes
      if (att_names != null) {
        for (int i = 0; i < att_names.length; i++) {
          String key = TypeCoercion.coerceToString(att_names[i]);
          String value = TypeCoercion.coerceToString(att_values[i]);
          if (key.equals("xmlns") || key.startsWith("xmlns:")) {
            uri = XMLConstants.XMLNS_ATTRIBUTE_NS_URI;
          } else {
            colon = key.indexOf(':');
            if (colon == -1)
              prefix = XMLConstants.DEFAULT_NS_PREFIX;
            else
              prefix = key.substring(0, colon);
            uri = env.getURI(prefix);
          }
          if (uri == null)
            elem.setAttribute(key, value);
          else
            elem.setAttributeNS(uri, key, value);
        }
      }

      // recursively create child nodes
      if (children != null) {
        for (Object child : children) {
          org.w3c.dom.Node node = XmlNode.coerceToNode(elctx, child);
          if (node != null) {
            elem.appendChild(node);
          }
        }
      }

      return XmlNode.valueOf(elem);
    } catch (DOMException ex) {
      throw new EvaluationException(elctx, ex);
    }
  }

  public static Object newArray(ELContext elctx, Object type, Object[] dims,
                                Object[] init) {
    if (dims == null || dims.length == 1) {
      return createOneDimensionArray(elctx, type, dims, init);
    } else {
      return createMultiDimensionArray(elctx, type, dims);
    }
  }

  private static Object createOneDimensionArray(ELContext elctx, Object type,
                                                Object[] dims, Object[] init) {
    int length = 0;
    if (dims != null) {
      length = TypeCoercion.coerceToInt(dims[0]);
    }
    if (init != null && length < init.length) {
      length = init.length;
    }

    Class<?> cls = getComponentType(elctx, type);
    Object result = Array.newInstance(cls, length);

    if (init != null) {
      if (result instanceof Object[] a) {
        System.arraycopy(init, 0, a, 0, init.length);
      } else {
        for (int i = 0; i < init.length; i++) {
          Array.set(result, i, TypeCoercion.coerce(init[i], cls));
        }
      }
    }

    return result;
  }

  private static Object createMultiDimensionArray(ELContext elctx, Object type,
                                                  Object[] dims) {
    assert dims != null && dims.length > 1;
    int[] d = new int[dims.length];
    for (int i = 0; i < d.length; i++) {
      d[i] = TypeCoercion.coerceToInt(dims[i]);
    }

    // TODO: populate initializer
    Class<?> t = getComponentType(elctx, type);
    return Array.newInstance(t, d);
  }

  private static Class<?> getComponentType(ELContext elctx, Object type) {
    if (type == null)
      return Object.class;
    if (type instanceof Class)
      return (Class<?>)type;
    try {
      return ELEngine.resolveJavaClass(elctx, (String)type);
    } catch (Exception ex) {
      return Object.class;
    }
  }

  public static java.util.Iterator<?> getIterator(Object coll) {
    if (coll instanceof Iterable<?>)
      return ((Iterable<?>)coll).iterator();
    if (coll instanceof Map<?, ?>)
      return ((Map<?, ?>)coll).entrySet().iterator(); // FIXME: need kv pair binding
    if (coll instanceof Object[])
      return Arrays.asList((Object[])coll).iterator();
    if (coll.getClass().isArray())
      return new ArrayItr(coll);
    if (coll instanceof String)
      return new ArrayItr(((String)coll).toCharArray());
    return null;
  }

  private static class ArrayItr implements Iterator<Object> {
    private int cursor;
    private final Object a;
    private final int length;

    ArrayItr(Object a) {
      this.a = a;
      this.length = Array.getLength(a);
    }

    @Override
    public boolean hasNext() {
      return cursor < length;
    }

    @Override
    public Object next() {
      int i = cursor;
      if (i >= length)
        throw new NoSuchElementException();
      cursor = i + 1;
      return Array.get(a, i);
    }
  }

  public static Throwable wrapException(Object t, ELContext elctx) {
    if (t instanceof RuntimeException)
      return (RuntimeException)t;
    if (t instanceof Throwable)
      return new UserException(elctx, (Throwable)t);
    if (t instanceof String)
      return new UserException(elctx, (String)t);
    return new UserException(elctx);
  }

  public static Object decodeObject(String src) {
    try {
      byte[] decoded = Base64.getDecoder().decode(src);
      ByteArrayInputStream bais = new ByteArrayInputStream(decoded);
      ObjectInputStream ois = new ObjectInputStream(bais);
      return ois.readObject();
    } catch (Exception e) {
      throw new RuntimeException(e);
    }
  }
