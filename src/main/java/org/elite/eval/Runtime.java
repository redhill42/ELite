    public static Object newMap(Object[] kvs) {
        java.util.LinkedHashMap<Object, Object> m = new java.util.LinkedHashMap<>();
        for (int i = 0; i < kvs.length; i += 2)
            m.put(kvs[i], kvs[i + 1]);
        return m;
    }

