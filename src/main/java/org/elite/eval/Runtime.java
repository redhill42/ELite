  public static void defineGlobal(Object value, String name,
                                  EvaluationContext env) {
    env.setVariable(name, new LiteralClosure(value));
  }

  public static Object resolveGlobal(String name, EvaluationContext env) {
    ELContext elctx = env.getELContext();

    ValueExpression expr = env.resolveVariable(name);
    if (expr != null) {
      return expr.getValue(elctx);
    }

    elctx.setPropertyResolved(false);
    Object value = elctx.getELResolver().getValue(elctx, null, name);
    if (elctx.isPropertyResolved()) {
      return value;
    }

    MethodClosure method = MethodResolver.getInstance(elctx)
      .resolveGlobalMethod(env.getFunctionMapper(), name);
    if (method != null) {
      return method;
    }

    throw new EvaluationException(elctx, _T(EL_UNDEFINED_IDENTIFIER, name));
  }

  public static Object storeGlobal(Object value, String name,
                                   EvaluationContext env) {
    ELContext elctx = env.getELContext();
    ValueExpression ve = env.resolveVariable(name);
    if (ve == null)
      throw new EvaluationException(elctx, _T(EL_UNDEFINED_IDENTIFIER, name));
    ve.setValue(elctx, value);
    return value;
  }

  public static Object loadProperty(Object base, Object key, ELContext c) {
    return ELNode.ACCESS.getValue(c, base, key);
  }

  public static Object storeProperty(Object value, Object base, Object key,
                                     ELContext c) {
    ELNode.ACCESS.setValue(c, base, key, value);
    return value;
  }

  private static EvaluationException
  reportMethodNotFound(ELContext elctx, Object base, String key,
                       MethodNotFoundException cause) {
    String msg = (cause == null) ? null : cause.getMessage();
    if (msg == null) {
      if (base instanceof ClosureObject) {
        base = ((ClosureObject)base).get_class().getName();
      } else if (base instanceof Closure) {
        base = base.toString();
      } else if (base != null) {
        base = base.getClass().getName();
      }
      msg = _T(EL_METHOD_NOT_FOUND, base, key);
    }
    return new EvaluationException(elctx, msg);
  }

  public static Object invokeMember(EvaluationContext env, Object base,
                                    Object key, Object[] args) {
    ELContext elctx = env.getELContext();
    if (base == null)
      return null;
    if (key == null)
      throw reportMethodNotFound(elctx, base, null, null);

    String name = TypeCoercion.coerceToString(key);

    // Route to compiled elite class.
    if (base instanceof DynamicDispatcher disp)
      return disp.__invoke__(env, name, args);

    Closure[] callArgs = ELEngine.getCallArgs(args);

    if (base == GlobalScope.SINGLETON) {
      Object target = loadProperty(base, key, elctx);
      try {
        return ELEngine.invokeTarget(elctx, target, callArgs);
      } catch (MethodNotFoundException e) {
        throw reportMethodNotFound(elctx, base, name, e);
      } catch (RuntimeException ex) {
        throw new EvaluationException(elctx, ex);
      }
    }

    // Invoke on legacy closure object for backward compatibility. Removed
    // when compiled class system is complete.
    if (base instanceof ClosureObject) {
      Object result = ((ClosureObject)base).invoke(elctx, name, callArgs);
      if (result != NO_RESULT)
        return result;
    }

    // Resolve and invoke method closure
    if (!(base instanceof MethodDelegate)) {
      MethodResolver resolver = MethodResolver.getInstance(elctx);
      MethodClosure method;
      boolean usebase = false;

      if (base == SystemScope.SINGLETON) {
        method = resolver.resolveSystemMethod(name);
      } else if (base instanceof Class) {
        method = resolver.resolveStaticMethod((Class<?>)base, name);
        if (method == null) {
          method = resolver.resolveMethod((Class<?>)base, name);
          if (method == null) {
            method = resolver.resolveMethod(Class.class, name);
            usebase = true;
          }
        }
      } else {
        method = resolver.resolveMethod(base.getClass(), name);
        usebase = true;
      }

      if (method != null) {
        try {
          if (usebase)
            return method.invoke(elctx, base, callArgs);
          else
            return method.invoke(elctx, callArgs);
        } catch (RuntimeException ex) {
          throw new EvaluationException(elctx, ex);
        }
      }
    }

    // Invoke dynamic object method.
    if (base instanceof MethodResolvable)
      return ((MethodResolvable)base).invoke(elctx, name, callArgs);

    throw reportMethodNotFound(elctx, base, name, null);
  }

  private static Object resolveTarget(EvaluationContext env, String id) {
    ELContext elctx = env.getELContext();

    ValueExpression expr = env.resolveVariable(id);
    if (expr != null) {
      return (expr instanceof LiteralClosure c) ? c.getValue(null) :
             (expr instanceof Closure) ? expr : expr.getValue(elctx);
    }

    MethodClosure method = MethodResolver.getInstance(elctx)
      .resolveGlobalMethod(env.getFunctionMapper(), id);
    if (method != null)
      return method;

    elctx.setPropertyResolved(false);
    return elctx.getELResolver().getValue(elctx, null, id);
  }

  public static Object invokeTarget(EvaluationContext env, String id,
                                    Object[] args) {
    ELContext elctx = env.getELContext();
    Object target = resolveTarget(env, id);
    if (target == null)
      throw new EvaluationException(elctx, _T(EL_UNDEFINED_IDENTIFIER, id));
    return ELEngine.callTarget(elctx, target, args);
  }

  public static Object invokeOperator(EvaluationContext env, String name,
                                      Object rhs) {
    if (rhs != null) {
      ELContext elctx = env.getELContext();
      Object result = ELNode.Unary.invokeOperator(elctx, name, rhs);
      if (result != NO_RESULT)
        return result;
    }
    return invokeTarget(env, name, new Object[]{rhs});
  }

  public static Object invokeOperator(EvaluationContext env, String name,
                                      Object lhs, Object rhs) {
    ELContext elctx = env.getELContext();
    Object result = ELNode.Binary.invokeOperator(elctx, name, lhs, rhs);
    if (result != NO_RESULT)
      return result;
    return invokeTarget(env, name, new Object[]{lhs, rhs});
  }

  public static Object invokeAssignOp(ELContext elctx, Integer op, Object lhs,
                                      Object rhs) {
    String opname = ELNode.opIdentifiers[op];
    Closure[] args = new Closure[1];
    Object result;

    // invoke assignment operator procedure
    if (lhs != null && opname != null) {
      if (lhs instanceof ClosureObject co) {
        args[0] = new LiteralClosure(rhs);
        result = co.invokeSpecial(elctx, opname.concat("="), args);
        if (result != NO_RESULT)
          return result;
      } else if (!(lhs instanceof Number)) {
        MethodClosure method = MethodResolver.getInstance(elctx)
          .resolveMethod(lhs.getClass(), opname.concat("="));
        if (method != null) {
          args[0] = new LiteralClosure(rhs);
          return method.invoke(elctx, lhs, args);
        }
      }
    }

    // do standard evaluation.
    return switch (op) {
      case Token.ADD    -> Builtin.__add__(elctx, lhs, rhs);
      case Token.SUB    -> Builtin.__sub__(elctx, lhs, rhs);
      case Token.MUL    -> Builtin.__mul__(elctx, lhs, rhs);
      case Token.DIV    -> Builtin.__div__(elctx, lhs, rhs);
      case Token.REM    -> Builtin.__rem__(elctx, lhs, rhs);
      case Token.POW    -> Builtin.__pow__(elctx, lhs, rhs);
      case Token.BITAND -> Builtin.__bitand__(elctx, lhs, rhs);
      case Token.BITOR  -> Builtin.__bitor__(elctx, lhs, rhs);
      case Token.XOR    -> Builtin.__xor__(elctx, lhs, rhs);
      case Token.CAT    -> Builtin.__cat__(elctx, lhs, rhs);
      case Token.SHL    -> Builtin.__shl__(elctx, lhs, rhs);
      case Token.SHR    -> Builtin.__shr__(elctx, lhs, rhs);
      case Token.USHR   -> Builtin.__ushr__(elctx, lhs, rhs);
      default -> null;
    };
  }

  public static Object newInstance(EvaluationContext env, String className,
                                   Object[] args, Map<Object, Object> props) {
    ELContext elctx = env.getELContext();
    Object cls = ELEngine.resolveClass(env, className);
    Closure[] argv = ELEngine.getCallArgs(args);

    Object obj;
    if (cls instanceof ClassDefinition) {
      obj = ((ClassDefinition)cls)._new(elctx, argv);
    } else {
      obj = ELEngine.newInstance(elctx, (Class<?>)cls, argv);
    }

    if (obj != null && props != null) {
      if (obj instanceof ClosureObject clo) {
        for (var e : props.entrySet()) {
          clo.setValue(elctx, e.getKey(), e.getValue());
        }
      } else {
        ELResolver resolver = elctx.getELResolver();
        for (var e : props.entrySet()) {
          resolver.setValue(elctx, obj, e.getKey(), e.getValue());
        }
      }
    }

    return obj;
  }

