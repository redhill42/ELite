  /**
   * Inner class for class compilation.
   */
  private class ClassCompiler {
    private final IRClass clazz;
    private final String className;
    private final String rootBaseClass;
    private final Map<String, IRFunction> vmap = new HashMap<>();

    ClassCompiler(IRClass clazz) {
      this.clazz = clazz;
      this.className = clazz.internalName;

      // Find the root base class. We will put some shared fields in this root
      // base class.
      if (clazz.base instanceof IRClass) {
        for (IRClass c = clazz; ; ) {
          if (c.base instanceof IRClass) {
            c = (IRClass)c.base;
          } else {
            rootBaseClass = c.internalName;
            break;
          }
        }
      } else {
        rootBaseClass = className;
      }
    }

    void compile() {
      Map<IRFunction, ELNode.DEFINE> fmap = new HashMap<>();
      for (ELNode.DEFINE var : clazz.node.cvars) {
        if (var.expr instanceof ELNode.LAMBDA fn) {
          fmap.put(fn.symbol.func, var);
        }
      }
      for (ELNode.DEFINE var : clazz.node.ivars) {
        if (var.expr instanceof ELNode.LAMBDA fn) {
          fmap.put(fn.symbol.func, var);
          vmap.put(var.id, fn.symbol.func);
        }
      }

      String baseName = clazz.base instanceof IRClass
                        ? ((IRClass)clazz.base).internalName
                        : ((Class<?>)clazz.base).getName();

      Set<String> interfaces = new LinkedHashSet<>();
      if (clazz.interfaces != null) {
        for (Class<?> i : clazz.interfaces)
          interfaces.add(i.getName());
      }

      if (isDataClass(clazz))
        interfaces.add("java.io.Serializable");

      boolean isComparable = false;
      if (!interfaces.contains("java.lang.Comparable") &&
          vmap.containsKey("<=>") ||
          ((vmap.containsKey("equals") || vmap.containsKey("==")) &&
           vmap.containsKey("<"))) {
        // If a class defines <=> procedure then this class is a Comparable
        // object. The compareTo method of Comparable interface forwards to the
        // <=> procedure.
        //
        // If a class defines equals and < procedure then this class is a
        // Comparable object. The compareTo method of Comparable interface is
        // implemented using equals and < procedure.
        isComparable = true;
        interfaces.add("java.lang.Comparable");
      }

      ELNode.METASET meta = clazz.node.symbol.def.meta;
      int access = meta == null ? 0 : meta.modifiers;
      if ((access & ACC_PRIVATE) == 0)
        access |= ACC_PUBLIC;
      ClassAssembly cc = new ClassAssembly(access | ACC_SUPER, className,
                                           baseName,
                                           interfaces.toArray(new String[0]));
      attachSource(cc, clazz.node.file);

      if (clazz.host != null)
        cc.getImpl().visitNestHost(AsmType.toInternalName(clazz.host.internalName));
      for (IRClass inner : clazz.inners)
        cc.getImpl().visitNestMember(AsmType.toInternalName(inner.internalName));

      // Add annotation for ELite class.
      cc.ANNOTATION(MetaClass.class, true)
        .FIELD("name", clazz.name)
        .end();

      // Add static and instance fields.
      for (ELNode.DEFINE var : clazz.node.cvars) {
        if (!(var.expr instanceof ELNode.LAMBDA) &&
            !(var.expr instanceof ELNode.CLASSDEF)) {
          access = var.meta == null ? ACC_PUBLIC : var.meta.modifiers;
          if ((access & (ACC_PRIVATE|ACC_PROTECTED)) == 0)
            access |= ACC_PUBLIC;
          cc.addField(access | ACC_STATIC, var.id, Object.class);
        }
      }
      if (clazz.node.vars != null) {
        for (ELNode.DEFINE var : clazz.node.vars) {
          access = var.meta == null ? ACC_PUBLIC : var.meta.modifiers;
          if ((access & (ACC_PRIVATE|ACC_PROTECTED)) == 0)
            access |= ACC_PUBLIC;
          cc.addField(access, var.id, Object.class);
        }
      }
      for (ELNode.DEFINE var : clazz.node.ivars) {
        if (!(var.expr instanceof ELNode.LAMBDA) &&
            !(var.expr instanceof ELNode.CLASSDEF)) {
          access = var.meta == null ? 0 : var.meta.modifiers;
          if ((access & (ACC_PRIVATE|ACC_PROTECTED)) == 0)
            access |= ACC_PUBLIC;
          cc.addField(access, var.id, Object.class);
        }
      }

      // Constructor.
      IRFunction initFunc = clazz.init_proc.symbol.func;
      access = clazz.isSingleton() ? ACC_PRIVATE : ACC_PUBLIC;
      MethodAssembly mc;

      if (clazz.outer != null) {
        String outerDescriptor = AsmType.toDescriptor(clazz.outer.internalName);
        cc.addField(ACC_FINAL | ACC_SYNTHETIC, "$outer", outerDescriptor);
        mc = cc.newMethod(access, "<init>",
          "(" + AsmType.getDescriptor(EvaluationContext.class) +
          AsmType.getDescriptor(Object[].class) +
          outerDescriptor + ")V", null);
        mc.THIS()
          .ALOAD(3)
          .PUTFIELD(className, "$outer", outerDescriptor);
      } else {
        mc = cc.newMethod(access, "<init>", Void.TYPE, EvaluationContext.class,
                          Object[].class);
      }

      AnnotationAssembly ac = mc.ANNOTATION(MetaMethod.class, true);
      ac.FIELD("name", clazz.name)
        .FIELD("arity", initFunc.paramCount())
        .FIELD("varargs", initFunc.isVarArgs())
        .ARRAY("parameterNames", initFunc.paramNames());
      emitDefaultValues(ac, initFunc.defaultValues());
      ac.end();

      if (className.equals(rootBaseClass)) {
        // Add $context field to save the ELContext for methods invoked without
        // an evaluation context, such as interface methods or Object methods.
        cc.addField(ACC_PROTECTED | ACC_FINAL | ACC_TRANSIENT, "$context",
                    ELContext.class);
        mc.THIS()
          .ALOAD(1)
          .INVOKEVIRTUAL(EvaluationContext.class, "getELContext",
                         ELContext.class)
          .PUTFIELD(className, "$context", ELContext.class);
      }

      new FunctionCompiler(initFunc, className, false, Void.TYPE, mc).compile();

      // Class initializer.
      if (clazz.clinit_proc != null || clazz.isSingleton()) {
        mc = cc.newMethod(ACC_PUBLIC | ACC_STATIC, "<clinit>", Void.TYPE);
        mc.NEW(EvaluationContext.class)
          .DUP()
          .INVOKESTATIC(ELEngine.class, "getCurrentELContext", ELContext.class)
          .INVOKESPECIAL(EvaluationContext.class, "<init>", Void.TYPE,
                         ELContext.class)
          .ASTORE(0);

        if (clazz.isSingleton()) {
          cc.addField(ACC_PUBLIC | ACC_STATIC | ACC_FINAL, "$singleton",
                      Object.class);
          mc.NEW(className)
            .DUP()
            .ALOAD(0)
            .ACONST_NULL()
            .INVOKESPECIAL(className, "<init>", Void.TYPE,
                           EvaluationContext.class, Object[].class)
            .PUTSTATIC(className, "$singleton", Object.class);
        }

        if (clazz.clinit_proc != null) {
          IRFunction clinitFunc = clazz.clinit_proc.symbol.func;
          mc.ICONST_0()
            .ANEWARRAY(Object.class)
            .ASTORE(1);
          new FunctionCompiler(clinitFunc, className, true, Void.TYPE, mc)
            .compile();
        } else {
          mc.RETURN();
          mc.end();
        }
      }

      // Generate member functions.
      for (IRFunction fn : clazz.functions()) {
        ELNode.DEFINE def = fmap.get(fn);
        if (def != null && (def.id.equals("toString") ||
                            def.id.equals("equals") ||
                            def.id.equals("hashCode")))
          continue; // generated differently

        access = def != null && def.meta != null ? def.meta.modifiers : 0;
        if ((access & (ACC_PRIVATE | ACC_PROTECTED)) == 0)
          access |= ACC_PUBLIC;
        if (def == null && fn.isStatic())
          access |= ACC_STATIC;
        mc = cc.newMethod(access, fn.internalName, Object.class,
                          EvaluationContext.class, Object[].class);

        // Add annotation for member attributes.
        ac = mc.ANNOTATION(MetaMethod.class, true);
        ac.FIELD("name", fn.name())
          .FIELD("arity", fn.paramCount())
          .FIELD("varargs", fn.isVarArgs())
          .ARRAY("parameterNames", fn.paramNames());
        emitDefaultValues(ac, fn.defaultValues());
        ac.end();

        if ((access & ACC_ABSTRACT) == 0) {
          new FunctionCompiler(fn, className, (access & ACC_STATIC) != 0,
                               Object.class, mc).compile();
        }
      }

      // Compile override methods derived from base class and interfaces.
      compileOverrideMethods(cc);

      // Generate toString method.
      if (vmap.containsKey("toString") || clazz.node.vars != null) {
        compileToStringMethod(cc);
      }

      // Generate equals method.
      if (vmap.containsKey("equals") || vmap.containsKey("==") ||
          clazz.node.vars != null) {
        compileEqualsMethod(cc);
      }

      // Generate hashCode method.
      if (vmap.containsKey("hashCode") || clazz.node.vars != null) {
        compileHashCodeMethod(cc);
      }

      // Generate compareTo method.
      if (isComparable) {
        compileCompareToMethod(cc);
      }

      consumer.acceptClass(className, cc.end());
    }

    private static boolean isDataClass(IRClass clazz) {
      ELNode.METASET meta = clazz.node.symbol.def.meta;
      return meta != null &&
        Arrays.stream(meta.metadata).anyMatch(md -> md.type.equals("data"));
    }

    private record MethodRecord(String name, List<Class<?>> paramTypes) {
      MethodRecord(Method m) {
        this(m.getName(), Arrays.asList(m.getParameterTypes()));
      }
    }

    private void compileOverrideMethods(ClassAssembly cc) {
      Map<MethodRecord, Method> methods = new HashMap<>();
      collectOverrideMethods(methods);
      if (methods.isEmpty())
        return;

      for (Method m : methods.values()) {
        IRFunction fn = vmap.get(m.getName());
        if (fn != null && fn.paramCount() == m.getParameterCount()) {
          MethodAssembly mc = cc.newMethod(ACC_PUBLIC, m);
          Class<?>[] paramTypes = m.getParameterTypes();
          Class<?> returnType = m.getReturnType();
          int ctxSlot = paramTypes.length + 1; // this, params..., ctx

          mc.THIS()
            .GETFIELD(rootBaseClass, "$context", ELContext.class);
          if (returnType != Void.TYPE && returnType != Object.class)
            mc.DUP(); // for coerce
          mc.ASTORE(ctxSlot);

          mc.THIS()
            .NEW(EvaluationContext.class)
            .DUP()
            .ALOAD(ctxSlot)
            .INVOKESPECIAL(EvaluationContext.class, "<init>", Void.TYPE,
                           ELContext.class)

            .PUSH(paramTypes.length)
            .ANEWARRAY(Object.class);
          for (int i = 0; i < paramTypes.length; i++) {
            mc.DUP()
              .PUSH(i)
              .XLOAD(i + 1, paramTypes[i])
              .BOX(paramTypes[i])
              .AASTORE();
          }

          mc.INVOKEVIRTUAL(className, m.getName(), Object.class,
                           EvaluationContext.class, Object[].class);
          if (returnType == Void.TYPE) {
            mc.POP().RETURN();
          } else if (returnType == Object.class) {
            mc.ARETURN();
          } else {
            mc.INVOKEDYNAMIC(FunctionCompiler.COERCE_BOOTSTRAP, "coerce",
                             AsmType.getMethodDescriptor(
                               returnType, ELContext.class, Object.class));
            mc.XRETURN(returnType);
          }
          mc.end();
        }
      }
    }

    private void collectOverrideMethods(Map<MethodRecord, Method> methods) {
      if (clazz.base instanceof Class<?> c && c != Object.class) {
        for (; c != Object.class; c = c.getSuperclass()) {
          for (Method m : c.getDeclaredMethods()) {
            int modifiers = m.getModifiers();
            if ((Modifier.isPublic(modifiers) ||
                 Modifier.isProtected(modifiers)) &&
                !Modifier.isStatic(modifiers) &&
                !Modifier.isFinal(modifiers)) {
              methods.putIfAbsent(new MethodRecord(m), m);
            }
          }
        }
      }

      if (clazz.interfaces != null) {
        for (Class<?> iface : clazz.interfaces) {
          for (Method m : iface.getMethods()) {
            int modifiers = m.getModifiers();
            if ((Modifier.isPublic(modifiers) ||
                 Modifier.isProtected(modifiers)) &&
                !Modifier.isStatic(modifiers))
              methods.putIfAbsent(new MethodRecord(m), m);
          }
        }
      }
    }

    private void compileToStringMethod(ClassAssembly cc) {
      MethodAssembly mc = cc.newMethod(ACC_PUBLIC, "toString", String.class);

      IRFunction fn = vmap.get("toString");
      if (fn != null) {
        mc.NEW(EvaluationContext.class)
          .DUP()
          .THIS()
          .GETFIELD(rootBaseClass, "$context", ELContext.class)
          .INVOKESPECIAL(EvaluationContext.class, "<init>", Void.TYPE,
                         ELContext.class)
          .ASTORE(1)
          .ICONST_0()
          .ANEWARRAY(Object.class)
          .ASTORE(2);
        new FunctionCompiler(fn, className, false, String.class, mc).compile();
      } else {
        mc.THIS()
          .GETFIELD(rootBaseClass, "$context", ELContext.class)
          .ASTORE(1);

        mc.NEW_INSTANCE(StringBuilder.class)
          .LDC(clazz.name + "(")
          .INVOKEVIRTUAL(StringBuilder.class, "append", StringBuilder.class,
                         String.class);

        assert clazz.node.vars != null;
        for (int i = 0; i < clazz.node.vars.length; i++) {
          Label b1 = new Label(), b2 = new Label();
          if (i > 0) {
            mc.LDC(", ")
              .INVOKEVIRTUAL(StringBuilder.class, "append", StringBuilder.class,
                             String.class);
          }
          mc.THIS()
            .GETFIELD(className, clazz.node.vars[i].id, Object.class)
            .DUP()
            .INSTANCEOF(String.class)
            .IFEQ(b1)
            .CHECKCAST(String.class)
            .INVOKESTATIC(ELUtils.class, "escape", StringBuilder.class,
                          StringBuilder.class, String.class)
            .GOTO(b2)
          .label(b1)
            .ALOAD(1)
            .SWAP()
            .INVOKEDYNAMIC(FunctionCompiler.COERCE_BOOTSTRAP, "coerce",
                           AsmType.getMethodDescriptor(
                             String.class, ELContext.class, Object.class))
            .INVOKEVIRTUAL(StringBuilder.class, "append", StringBuilder.class,
                           String.class)
          .label(b2);
        }

        mc.LDC(")")
          .INVOKEVIRTUAL(StringBuilder.class, "append", StringBuilder.class,
                         String.class)
          .INVOKEVIRTUAL(StringBuilder.class, "toString", String.class)
          .ARETURN()
          .end();
      }
    }

    private void compileEqualsMethod(ClassAssembly cc) {
      MethodAssembly mc = cc.newMethod(ACC_PUBLIC, "equals", Boolean.TYPE,
                                       Object.class);

      if (vmap.containsKey("equals") && !vmap.containsKey("==")) {
        mc.NEW(EvaluationContext.class)
          .DUP()
          .THIS()
          .GETFIELD(rootBaseClass, "$context", ELContext.class)
          .INVOKESPECIAL(EvaluationContext.class, "<init>", Void.TYPE,
                         ELContext.class)
          .ASTORE(1)
          .ICONST_1()
          .ANEWARRAY(Object.class)
          .DUP()
          .ICONST_0()
          .ALOAD(1)
          .AASTORE()
          .ASTORE(2);

        IRFunction fn = vmap.getOrDefault("equals", vmap.get("=="));
        new FunctionCompiler(fn, className, false, Boolean.TYPE, mc).compile();
      } else {
        Label exit = new Label();
        mc.ALOAD(1)
          .INSTANCEOF(className)
          .IFEQ(exit)
          .ALOAD(1)
          .CHECKCAST(className)
          .ASTORE(2);

        assert clazz.node.vars != null;
        for (ELNode.DEFINE var : clazz.node.vars) {
          mc.THIS()
            .GETFIELD(className, var.id, Object.class)
            .ALOAD(2)
            .GETFIELD(className, var.id, Object.class)
            .INVOKESTATIC(Objects.class, "equals", Boolean.TYPE, Object.class,
                          Object.class)
            .IFEQ(exit);
        }

        mc.TRUE()
          .IRETURN();

        mc.label(exit)
          .FALSE()
          .IRETURN()
          .end();
      }
    }

    private void compileHashCodeMethod(ClassAssembly cc) {
      MethodAssembly mc = cc.newMethod(ACC_PUBLIC, "hashCode", Integer.TYPE);

      IRFunction fn = vmap.get("hashCode");
      if (fn != null) {
        mc.NEW(EvaluationContext.class)
          .DUP()
          .THIS()
          .GETFIELD(rootBaseClass, "$context", ELContext.class)
          .INVOKESPECIAL(EvaluationContext.class, "<init>", Void.TYPE,
                         ELContext.class)
          .ASTORE(1)
          .ICONST_0()
          .ANEWARRAY(Object.class)
          .ASTORE(2);
        new FunctionCompiler(fn, className, false, Integer.TYPE, mc).compile();
      } else {
        assert clazz.node.vars != null;
        mc.ICONST_1();
        for (ELNode.DEFINE var : clazz.node.vars) {
          Label b1 = new Label(), b2 = new Label();
          mc.PUSH(31)
            .IMUL()
            .THIS()
            .GETFIELD(className, var.id, Object.class)
            .DUP()
            .IFNONNULL(b1)
            .POP()
            .ICONST_0()
            .GOTO(b2)
            .label(b1)
            .INVOKEVIRTUAL(Object.class, "hashCode", Integer.TYPE)
            .label(b2)
            .IADD();
        }
        mc.IRETURN().end();
      }
    }

    private void compileCompareToMethod(ClassAssembly cc) {
      if (vmap.containsKey("<=>")) {
        // Delegate compareTo to the <=> procedure.
        IRFunction threeWay = vmap.get("<=>");
        cc.newMethod(ACC_PUBLIC, "compareTo", Integer.TYPE, Object.class)
          .THIS()
          .NEW(EvaluationContext.class)
          .DUP()
          .THIS()
          .GETFIELD(rootBaseClass, "$context", ELContext.class)
          .INVOKESPECIAL(EvaluationContext.class, "<init>", Void.TYPE,
                         ELContext.class)
          .ICONST_1()
          .ANEWARRAY(Object.class)
          .DUP()
          .ICONST_0()
          .ALOAD(1)
          .CHECKCAST(className)
          .AASTORE()
          .INVOKEVIRTUAL(className, threeWay.internalName, Object.class,
                         EvaluationContext.class, Object[].class)
          .UNBOX(Integer.TYPE)
          .IRETURN()
          .end();
      } else {
        IRFunction less = vmap.get("<");
        assert less != null;
        Label b1 = new Label(), b2 = new Label(), exit = new Label();

        cc.newMethod(ACC_PUBLIC, "compareTo", Integer.TYPE, Object.class)
          .THIS()
          .ALOAD(1)
          .INVOKEVIRTUAL(Object.class, "equals", Boolean.TYPE, Object.class)
          .IFEQ(b1)
          .ICONST_0()
          .GOTO(exit)
          .label(b1)
          .THIS()
          .NEW(EvaluationContext.class)
          .DUP()
          .THIS()
          .GETFIELD(rootBaseClass, "$context", ELContext.class)
          .INVOKESPECIAL(EvaluationContext.class, "<init>", Void.TYPE,
                         ELContext.class)
          .ICONST_1()
          .ANEWARRAY(Object.class)
          .DUP()
          .ICONST_0()
          .ALOAD(1)
          .CHECKCAST(className)
          .AASTORE()
          .INVOKEVIRTUAL(className, less.internalName, Object.class,
                         EvaluationContext.class, Object[].class)
          .UNBOX(Boolean.TYPE)
          .IFEQ(b2)
          .ICONST_M1()
          .GOTO(exit)
          .label(b2)
          .ICONST_1()
          .label(exit)
          .IRETURN()
          .end();
      }
    }
  }

