  private static class JITBytecodeConsumer implements BytecodeConsumer {
    private final DynamicClassLoader loader;
    private Class<?> programClass;

    JITBytecodeConsumer(DynamicClassLoader loader) {
      this.loader = loader;
    }

    @Override
    public void acceptProgram(String className, byte[] bytecode) {
      programClass = loader.addClass(className, bytecode);
    }

    @Override
    public void acceptClass(String className, byte[] bytecode) {
      loader.addClass(className, bytecode);
    }

    IRCompiledFunction complete() {
      try {
        MethodHandles.Lookup lookup = MethodHandles.lookup();
        MethodHandle target = lookup.findStatic(
          programClass, "fn$main", MethodType.methodType(
            Object.class, EvaluationContext.class, Object[].class));
        return new IRCompiledFunction(target);
      } catch (NoSuchMethodException | IllegalAccessException e) {
        throw new RuntimeException(_T(IR_BYTECODE_COMPILE_FAILED), e);
      }
    }
  }
